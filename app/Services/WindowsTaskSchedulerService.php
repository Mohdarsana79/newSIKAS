<?php

namespace App\Services;

use Illuminate\Support\Facades\Log;
use InvalidArgumentException;
use Symfony\Component\Process\Process;
use Throwable;

class WindowsTaskSchedulerService
{
    public const TASK_NAME = 'newSIKAS-AutoBackup';

    /**
     * Memecahkan path binary PHP CLI yang valid (bukan httpd.exe / php-cgi.exe saat dipanggil lewat web server).
     */
    public function resolvePhpCliBinary(): string
    {
        $binary = (string) PHP_BINARY;
        $baseLower = strtolower(basename($binary));

        if (
            PHP_SAPI === 'cli'
            && $binary !== ''
            && is_file($binary)
            && str_starts_with($baseLower, 'php')
            && ! str_starts_with($baseLower, 'php-cgi')
        ) {
            return PHP_OS_FAMILY === 'Windows' ? str_replace('/', '\\', $binary) : $binary;
        }

        if (PHP_OS_FAMILY === 'Windows') {
            $candidates = [
                rtrim((string) PHP_BINDIR, '\\/').'\\php.exe',
                rtrim(dirname($binary), '\\/').'\\php.exe',
            ];

            foreach ($candidates as $candidate) {
                if ($candidate !== '\\php.exe' && is_file($candidate)) {
                    return str_replace('/', '\\', $candidate);
                }
            }

            try {
                $where = new Process(['where.exe', 'php']);
                $where->setTimeout(4);
                $where->run();
                if ($where->isSuccessful()) {
                    $lines = preg_split('/\r?\n/', trim($where->getOutput())) ?: [];
                    foreach ($lines as $line) {
                        $line = trim($line);
                        if ($line !== '' && is_file($line)) {
                            return str_replace('/', '\\', $line);
                        }
                    }
                }
            } catch (Throwable) {
                // Fallback ke 'php'
            }

            return 'php';
        }

        $unixCandidate = rtrim((string) PHP_BINDIR, '/').'/php';

        return is_file($unixCandidate) ? $unixCandidate : 'php';
    }

    /**
     * Path berkas pembungkus VBS senyap (menjalankan `artisan schedule:run` tanpa jendela CMD berkedip).
     */
    public function getRunnerScriptPath(): string
    {
        return storage_path('app/auto-backup-runner.vbs');
    }

    /**
     * Memvalidasi bahwa path aman untuk dimasukkan ke VBScript / schtasks tanpa karakter injeksi.
     */
    protected function assertSafeWindowsPath(string $path, string $label): string
    {
        $trimmed = trim($path);
        if ($trimmed === '') {
            throw new InvalidArgumentException("{$label} tidak boleh kosong.");
        }

        // Tolak karakter kontrol (\x00-\x1f termasuk \r\n) dan metakarakter VBS/shell (", %, &, |, <, >)
        if (preg_match('/[\x00-\x1f"%&|<>]/', $trimmed) === 1) {
            throw new InvalidArgumentException("{$label} mengandung karakter yang tidak diizinkan untuk skrip otomatis.");
        }

        return str_replace('/', '\\', $trimmed);
    }

    /**
     * Menghasilkan isi script VBScript senyap dinamis berdasarkan lokasi PHP CLI & base_path() aktif saat runtime.
     */
    public function buildSilentVbsContent(?string $phpBinary = null, ?string $artisanPath = null): string
    {
        $php = $this->assertSafeWindowsPath($phpBinary ?: $this->resolvePhpCliBinary(), 'Path PHP CLI');
        $artisan = $this->assertSafeWindowsPath($artisanPath ?: base_path('artisan'), 'Path Artisan');

        $command = '""'.$php.'"" ""'.$artisan.'"" schedule:run';

        return implode("\r\n", [
            '\' Auto-generated by newSIKAS — menjalankan Laravel Scheduler secara senyap (window style 0)',
            'Option Explicit',
            'Dim shell',
            'Set shell = CreateObject("WScript.Shell")',
            'shell.Run "'.$command.'", 0, False',
            'Set shell = Nothing',
            '',
        ]);
    }

    /**
     * Menjalankan `php artisan backup:auto-run` secara detached (non-blocking) di latar belakang
     * agar HTTP heartbeat kembali instan tanpa mengunci worker web atau Laravel session.
     */
    public function spawnBackgroundAutoRun(): bool
    {
        try {
            $php = $this->resolvePhpCliBinary();
            $artisan = base_path('artisan');

            if (PHP_OS_FAMILY === 'Windows') {
                $safePhp = $this->assertSafeWindowsPath($php, 'Path PHP CLI');
                $safeArtisan = $this->assertSafeWindowsPath($artisan, 'Path Artisan');
                $oneShotVbs = storage_path('app/auto-backup-oneshot.vbs');
                $vbs = implode("\r\n", [
                    'Option Explicit',
                    'Dim shell',
                    'Set shell = CreateObject("WScript.Shell")',
                    'shell.Run """'.$safePhp.'"" ""'.$safeArtisan.'"" backup:auto-run", 0, False',
                    'Set shell = Nothing',
                    '',
                ]);

                if (@file_put_contents($oneShotVbs, $vbs) === false) {
                    return false;
                }

                $safeVbs = $this->assertSafeWindowsPath($oneShotVbs, 'Path Runner VBS');
                $handle = @popen('start "" /B wscript.exe //B //NoLogo "'.$safeVbs.'"', 'r');
                if (is_resource($handle)) {
                    @pclose($handle);

                    return true;
                }

                return false;
            }

            $cmd = escapeshellarg($php).' '.escapeshellarg($artisan).' backup:auto-run > /dev/null 2>&1 &';
            $handle = @popen($cmd, 'r');
            if (is_resource($handle)) {
                @pclose($handle);

                return true;
            }

            return false;
        } catch (Throwable $e) {
            Log::warning('WindowsTaskSchedulerService spawnBackgroundAutoRun gagal.', ['error' => $e->getMessage()]);

            return false;
        }
    }

    /**
     * Memeriksa status pendaftaran Windows Task Scheduler secara dinamis.
     *
     * @return array{
     *   supported: bool,
     *   installed: bool,
     *   path_matches_current: bool,
     *   task_name: string,
     *   runner_path: string,
     *   message: string
     * }
     */
    public function getStatus(): array
    {
        $runnerPath = str_replace('/', '\\', $this->getRunnerScriptPath());

        if (PHP_OS_FAMILY !== 'Windows') {
            return [
                'supported' => false,
                'installed' => false,
                'path_matches_current' => false,
                'task_name' => self::TASK_NAME,
                'runner_path' => $runnerPath,
                'message' => 'Aktivasi 1-klik Windows Task Scheduler hanya tersedia pada sistem Windows. Pada server Linux gunakan Cron Job.',
            ];
        }

        try {
            $process = new Process(['schtasks', '/Query', '/TN', self::TASK_NAME, '/FO', 'LIST', '/V']);
            $process->setTimeout(6);
            $process->run();

            if (! $process->isSuccessful()) {
                return [
                    'supported' => true,
                    'installed' => false,
                    'path_matches_current' => false,
                    'task_name' => self::TASK_NAME,
                    'runner_path' => $runnerPath,
                    'message' => 'Background Windows Task belum aktif (Auto-Backup tetap otomatis berjalan setiap kali aplikasi SIKAS dibuka).',
                ];
            }

            $output = $process->getOutput();
            $pathMatches = stripos($output, $runnerPath) !== false && is_file($runnerPath);

            if (! $pathMatches) {
                return [
                    'supported' => true,
                    'installed' => true,
                    'path_matches_current' => false,
                    'task_name' => self::TASK_NAME,
                    'runner_path' => $runnerPath,
                    'message' => 'Task Windows terdeteksi, namun mengarah ke lokasi instalasi lama. Klik Perbarui Task untuk menyinkronkan ke folder aplikasi saat ini.',
                ];
            }

            return [
                'supported' => true,
                'installed' => true,
                'path_matches_current' => true,
                'task_name' => self::TASK_NAME,
                'runner_path' => $runnerPath,
                'message' => 'Background Windows Task aktif & sinkron dengan folder aplikasi saat ini (tetap berjalan walau browser ditutup).',
            ];
        } catch (Throwable $e) {
            Log::warning('WindowsTaskSchedulerService getStatus gagal.', ['error' => $e->getMessage()]);

            return [
                'supported' => true,
                'installed' => false,
                'path_matches_current' => false,
                'task_name' => self::TASK_NAME,
                'runner_path' => $runnerPath,
                'message' => 'Status Windows Task tidak dapat diperiksa otomatis. Auto-Backup tetap otomatis berjalan saat aplikasi dibuka.',
            ];
        }
    }

    /**
     * Mendaftarkan (atau memperbarui) Windows Task Scheduler secara dinamis & senyap dalam 1 klik.
     *
     * @return array{success: bool, message: string, status: array<string, mixed>}
     */
    public function install(): array
    {
        if (PHP_OS_FAMILY !== 'Windows') {
            return [
                'success' => false,
                'message' => 'Fitur aktivasi 1-klik hanya tersedia pada Windows.',
                'status' => $this->getStatus(),
            ];
        }

        try {
            $runnerPath = $this->assertSafeWindowsPath($this->getRunnerScriptPath(), 'Path Runner VBS');
            $taskAction = 'wscript.exe //B //NoLogo "'.$runnerPath.'"';

            if (strlen($taskAction) > 261) {
                return [
                    'success' => false,
                    'message' => 'Lokasi folder instalasi aplikasi terlalu panjang untuk Windows Task Scheduler (> 261 karakter). Auto-Backup tetap berjalan otomatis saat aplikasi dibuka.',
                    'status' => $this->getStatus(),
                ];
            }

            $runnerDir = dirname($runnerPath);
            if (! is_dir($runnerDir) && ! @mkdir($runnerDir, 0755, true) && ! is_dir($runnerDir)) {
                return [
                    'success' => false,
                    'message' => 'Gagal membuat direktori penyimpanan untuk runner scheduler.',
                    'status' => $this->getStatus(),
                ];
            }

            $vbsContent = $this->buildSilentVbsContent();
            if (@file_put_contents($runnerPath, $vbsContent) === false) {
                return [
                    'success' => false,
                    'message' => 'Gagal menulis berkas runner scheduler senyap.',
                    'status' => $this->getStatus(),
                ];
            }

            $process = new Process([
                'schtasks',
                '/Create',
                '/SC',
                'MINUTE',
                '/MO',
                '1',
                '/TN',
                self::TASK_NAME,
                '/TR',
                $taskAction,
                '/F',
            ]);
            $process->setTimeout(10);
            $process->run();

            if (! $process->isSuccessful()) {
                Log::warning('WindowsTaskSchedulerService install gagal.', [
                    'stderr' => $process->getErrorOutput(),
                    'stdout' => $process->getOutput(),
                ]);

                return [
                    'success' => false,
                    'message' => 'Gagal mendaftarkan Windows Task Scheduler. Pastikan akun Windows memiliki izin membuat Task atau jalankan aplikasi sebagai Administrator.',
                    'status' => $this->getStatus(),
                ];
            }

            return [
                'success' => true,
                'message' => 'Background Windows Task berhasil diaktifkan! Auto-Backup kini tetap berjalan senyap di latar belakang meski browser ditutup.',
                'status' => $this->getStatus(),
            ];
        } catch (InvalidArgumentException $e) {
            return [
                'success' => false,
                'message' => $e->getMessage(),
                'status' => $this->getStatus(),
            ];
        } catch (Throwable $e) {
            Log::warning('WindowsTaskSchedulerService install exception.', ['error' => $e->getMessage()]);

            return [
                'success' => false,
                'message' => 'Terjadi kesalahan saat mengaktifkan Windows Task Scheduler.',
                'status' => $this->getStatus(),
            ];
        }
    }

    /**
     * Menghapus Windows Task Scheduler `newSIKAS-AutoBackup` beserta script VBS pembungkus.
     *
     * @return array{success: bool, message: string, status: array<string, mixed>}
     */
    public function remove(): array
    {
        if (PHP_OS_FAMILY !== 'Windows') {
            return [
                'success' => false,
                'message' => 'Fitur ini hanya tersedia pada Windows.',
                'status' => $this->getStatus(),
            ];
        }

        try {
            $process = new Process(['schtasks', '/Delete', '/TN', self::TASK_NAME, '/F']);
            $process->setTimeout(8);
            $process->run();

            if (! $process->isSuccessful()) {
                $combined = strtolower($process->getErrorOutput().' '.$process->getOutput());
                if (str_contains($combined, 'cannot find') || str_contains($combined, 'does not exist')) {
                    $runnerPath = $this->getRunnerScriptPath();
                    if (is_file($runnerPath)) {
                        @unlink($runnerPath);
                    }

                    return [
                        'success' => true,
                        'message' => 'Background Windows Task sudah tidak aktif.',
                        'status' => $this->getStatus(),
                    ];
                }

                // Jangan hapus file .vbs jika penghapusan task gagal agar task tidak menjadi yatim
                return [
                    'success' => false,
                    'message' => 'Gagal menghapus Windows Task Scheduler. Pastikan Anda memiliki izin yang cukup.',
                    'status' => $this->getStatus(),
                ];
            }

            $runnerPath = $this->getRunnerScriptPath();
            if (is_file($runnerPath)) {
                @unlink($runnerPath);
            }

            return [
                'success' => true,
                'message' => 'Background Windows Task berhasil dinonaktifkan. Auto-Backup tetap otomatis berjalan saat aplikasi dibuka.',
                'status' => $this->getStatus(),
            ];
        } catch (Throwable $e) {
            Log::warning('WindowsTaskSchedulerService remove exception.', ['error' => $e->getMessage()]);

            return [
                'success' => false,
                'message' => 'Terjadi kesalahan saat menonaktifkan Windows Task Scheduler.',
                'status' => $this->getStatus(),
            ];
        }
    }
}
